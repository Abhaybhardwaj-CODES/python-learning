import numpy as np
# Addition of numbers
a = np.array([1, 2, 3])
a + 5
print("Addition of 5 to each element:", a + 5)
# Subtraction of numbers
b = np.array([10, 20, 30])
b - 5
print("Subtraction of 5 from each element:", b - 5)
# Multiplication of numbers
c = np.array([2, 4, 6])
c * 3
print("Multiplication of 3 with each element:", c * 3)
# Division of numbers
d = np.array([10, 20, 30])
d / 2
print("Division of each element by 2:", d / 2)
